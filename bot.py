@dp.message(CommandStart())
async def start(message: types.Message):
    await message.answer(
        "🔮 **Добро пожаловать в Таро Уэйта**\n\n"
        "Выбери тему расклада 👇\n\n"
        "✨ *Пример вопроса:*\n"
        "«Что меня ждёт в ближайшей перспективе?»\n"
        "«Как ко мне относится Имя человека?»\n"
        "«Стоит ли начинать проект?»\n\n"
        "Ты можешь задать **любой вопрос**, а карты дадут ответ.",
        reply_markup=menu,
        parse_mode="Markdown"
    )


# =========================
# ОБРАБОТКА ВЫБОРА РАСКЛАДА
# =========================
@dp.callback_query()
async def choose_spread(callback: types.CallbackQuery, state: FSMContext):
    spread = callback.data  # love, money, future, three
    await state.update_data(spread=spread)
    await callback.message.answer(
        "✨ **Напиши свой вопрос**\n\n"
        "Примеры:\n"
        "• «Что меня ждёт в ближайшей перспективе?»\n"
        "• «Как ко мне относится Анна?»\n"
        "• «Стоит ли менять работу?»\n\n"
        "Просто отправь сообщение."
    )
    await state.set_state(TarotState.waiting_question)
    await callback.answer()


# =========================
# ГАДАНИЕ НА ВОПРОС
# =========================
@dp.message(TarotState.waiting_question)
async def tarot_reading(message: types.Message, state: FSMContext):
    data = await state.get_data()
    spread = data.get("spread")
    question = message.text.strip()

    if not question:
        await message.answer("❓ Напиши вопрос, пожалуйста.")
        return

    if spread == "three":
        positions = ["Прошлое", "Настоящее", "Будущее"]
        text = f"🔮 **Расклад «3 карты»**\n📩 Вопрос: _{question}_\n\n"
        for pos in positions:
            card, pos_status, meaning = draw_one_card()
            text += f"🃏 **{pos}**\nКарта: *{card}*\nПоложение: *{pos_status}*\nЗначение: {meaning}\n\n"
        await message.answer(text, parse_mode="Markdown")
    else:
        theme_map = {
            "love": "❤️ Любовный расклад",
            "money": "💰 Финансовый расклад",
            "future": "🔮 Расклад на будущее"
        }
        card, pos_status, meaning = draw_one_card()
        text = (
            f"{theme_map.get(spread, '🔮 Расклад Таро')}\n\n"
            f"📩 Вопрос: _{question}_\n\n"
            f"🃏 Карта: *{card}*\n"
            f"📌 Положение: *{pos_status}*\n\n"
            f"✨ Трактовка:\n{meaning}\n\n"
            f"🌙 Помни: карта показывает энергию момента, а твой выбор меняет будущее."
        )
        await message.answer(text, parse_mode="Markdown")

    await state.clear()


