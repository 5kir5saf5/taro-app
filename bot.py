@dp.message(TarotState.waiting_question)
async def ask_tarot(message: types.Message, state: FSMContext):
    uid = message.from_user.id
    data = await state.get_data()
    spread = data.get("spread", "single")
    theme = data.get("theme", "general")
    question = message.text.strip()
    
    user = get_user(uid)
    if user["questions_left"] <= 0:
        await message.answer(
            "❌ У тебя закончились вопросы!\nПополни баланс в меню.",
            reply_markup=main_keyboard
        )
        await state.clear()
        return
    
    # Списываем вопрос
    new_balance = user["questions_left"] - 1
    update_user(uid, "questions_left", new_balance)
    update_user(uid, "total_asked", user.get("total_asked", 0) + 1)
    
    tip = random.choice(tips)
    
    if spread == "three":
        text = get_three_reading(question, theme)
        text += f"\n\n📊 Осталось вопросов: {new_balance}\n✨ {tip}"
    else:
        name, pos, meaning = draw_card()
        text = get_single_reading(name, pos, meaning, theme, question)
        text += f"\n\n📊 Осталось вопросов: {new_balance}\n✨ {tip}"
    
    await message.answer(text, parse_mode="Markdown", reply_markup=main_keyboard)
    await state.clear()

