# =========================
# ФУНКЦИЯ ГАДАНИЯ (1 карта)
# =========================
def draw_one_card():
    card_name = random.choice(list(cards.keys()))
    is_reversed = random.choice([True, False])
    if is_reversed:
        return card_name, "перевернутая", cards[card_name]["reversed"]
    else:
        return card_name, "прямая", cards[card_name]["upright"]


