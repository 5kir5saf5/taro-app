def get_theme(theme_str):
    if theme_str == "theme_love":
        return "love"
    elif theme_str == "theme_money":
        return "money"
    elif theme_str == "theme_career":
        return "career"
    return "general"

def draw_card():
    name = random.choice(list(cards.keys()))
    is_rev = random.choice([True, False])
    meaning = cards[name]["reversed" if is_rev else "upright"]
    pos = "перевёрнутая" if is_rev else "прямая"
    return name, pos, meaning

def get_single_reading(card_name, position, meaning, theme, question):
    theme_name = get_theme(theme)
    
    # Сердечная вставка
    if "любов" in question.lower() or "отнош" in question.lower() or theme_name == "love":
        intro = f"💕 Твой вопрос о сердечных делах, {card_name} обращается к глубине твоих чувств.\n\n"
    elif "деньг" in question.lower() or "финанс" in question.lower() or theme_name == "money":
        intro = f"💰 Финансовый вопрос — {card_name} открывает поток возможностей.\n\n"
    elif "работ" in question.lower() or "карьер" in question.lower() or theme_name == "career":
        intro = f"💼 Деловой вопрос — {card_name} указывает на твой потенциал.\n\n"
    else:
        intro = f"🔮 По твоему вопросу {card_name} даёт следующий ответ.\n\n"
    
    return intro + meaning + f"\n\n📩 Вопрос: «{question}»\nПосмотри на карту: она отражает энергию момента, но твой выбор всегда сильнее."

def get_three_reading(question, theme):
    cards_data = [draw_card() for _ in range(3)]
    positions = ["☄️ ПРОШЛОЕ", "🌟 НАСТОЯЩЕЕ", "🌙 БУДУЩЕЕ"]
    text = ""
    for i, (name, pos_c, meaning) in enumerate(cards_data):
        text += f"🃏 {positions[i]}: {name} ({pos_c})\n✨ {meaning}\n\n"
    
    # Общая трактовка
    all_meanings = " ".join([m for _, _, m in cards_data])
    if "любов" in question.lower():
        general = f"💞 В любви три карты говорят: {all_meanings[:200]}... Твоя ситуация развивается к гармонии, если отпустишь контроль. Доверься чувствам."
    elif "деньг" in question.lower():
        general = f"💰 Деньги: {all_meanings[:200]}... Финансовый поток усилится к концу месяца. Избегай крупных трат сейчас."
    elif "работ" in question.lower():
        general = f"💼 Карьера: {all_meanings[:200]}... Перемены в работе неизбежны. Будь готов к новым задачам."
    else:
        general = f"🔮 Общий поток: {all_meanings[:200]}... Судьба ведёт тебя через опыт. Главное не застывать на месте."
    
    text += f"🌟 ОБЩАЯ ТРАКТОВКА:\n{general}\n\n"
    text += f"💫 {random.choice(tips)}\n\n📩 Вопрос: {question}"
    return text

