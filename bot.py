DATA_FILE = "data.json"

def load_data():
    if os.path.exists(DATA_FILE):
        with open(DATA_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return {"users": {}, "pending_payments": []}

def save_data(data):
    with open(DATA_FILE, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def get_user(user_id):
    data = load_data()
    uid = str(user_id)
    if uid not in data["users"]:
        data["users"][uid] = {
            "questions_left": 1,
            "last_free_date": None,
            "total_asked": 0
        }
        save_data(data)
    return data["users"][uid]

def update_user(user_id, key, value):
    data = load_data()
    uid = str(user_id)
    if uid not in data["users"]:
        get_user(user_id)
    data["users"][uid][key] = value
    save_data(data)

def can_get_free(user_id):
    user = get_user(user_id)
    last = user.get("last_free_date")
    if not last:
        return True
    try:
        last_date = datetime.fromisoformat(last)
        return datetime.now() - last_date >= timedelta(days=1)
    except:
        return True

def use_free_question(user_id):
    if can_get_free(user_id):
        update_user(user_id, "last_free_date", datetime.now().isoformat())
        return True
    return False

